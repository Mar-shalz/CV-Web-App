// Builds two all in one SQL files from supabase/migrations (the source of truth):
//   supabase/sql/app_schema.sql   everything the app needs
//   supabase/sql/back_office.sql  staff roles, truth reports, AI call log, audit extras
// For a brand new Supabase project: run app_schema.sql, then back_office.sql.
// A project that already ran the numbered files must not run these (see verify_setup.sql).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const STAFF_MARKER = "-- Staff who leave and delete their own account don't block it.";

let app = "";
let office = "";
for (const f of files) {
  const sql = readFileSync(`${dir}/${f}`, "utf8").trimEnd();
  const block = (body) => `\n-- ===========================================================================\n-- From ${f}\n-- ===========================================================================\n${body.trim()}\n`;
  if (f.startsWith("0002_")) {
    office += block(sql);
  } else if (sql.includes(STAFF_MARKER)) {
    const [appPart, staffPart] = sql.split(STAFF_MARKER);
    app += block(appPart);
    office += block(`${STAFF_MARKER}${staffPart}`);
  } else {
    app += block(sql);
  }
}

const header = (title, order) => `-- ${title}
-- Generated by \`npm run sql:bundle\` from supabase/migrations. Do not edit by hand.
-- For a NEW Supabase project only. ${order}
-- If your project already ran the numbered migration files, don't run this: run
-- supabase/verify_setup.sql and apply only the files it marks NOT APPLIED.
`;

mkdirSync("supabase/sql", { recursive: true });
writeFileSync("supabase/sql/app_schema.sql", header("App schema: every table, policy, function and bucket the app needs.", "Run this first.") + app);
writeFileSync("supabase/sql/back_office.sql", header("Back office: staff roles, truth reports, AI call log and audit extras.", "Run this after app_schema.sql.") + office);
console.log(`Wrote supabase/sql/app_schema.sql and supabase/sql/back_office.sql from ${files.length} migrations.`);
